# 1. Ordered daily file names:
# Choice: List
# Why: Lists maintain order and allow adding new items dynamically (mutable).

# 2. Unique customer IDs:
# Choice: Set
# Why: Sets automatically eliminate duplicates and offer fast lookups.

# 3. Fixed latitude and longitude:
# Choice: Tuple
# Why: Coordinates are fixed pairs that should not be changed (immutable).

# 4. Customer ID mapped to customer details:
# Choice: Dictionary
# Why: Dictionaries allow key-value mapping to look up details by an ID key.
