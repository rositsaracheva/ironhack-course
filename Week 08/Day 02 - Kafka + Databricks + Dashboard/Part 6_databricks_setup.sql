-- I make sure I am using my default Unity Catalog ('workspace' in Databricks Free Edition).
USE CATALOG workspace;

-- I create a dedicated schema (database) called 'kafka_demo' for this real-time streaming project.
CREATE SCHEMA IF NOT EXISTS workspace.kafka_demo;

-- I switch into the 'kafka_demo' schema so the table below is created inside it.
USE SCHEMA kafka_demo;

-- I create (or replace) the 'orders' Delta table with columns matching the exact JSON fields
-- produced by Part 4_producer.py:
--   order_id      -> integer order number (1, 2, 3, ...)
--   customer_name -> random customer full name generated by Faker
--   city          -> order city ('Mumbai', 'Delhi', 'Bangalore', 'Pune')
--   product       -> product category ('Laptop', 'Phone', 'Tablet', 'Headphones')
--   amount        -> order price in decimal format (DOUBLE)
--   payment_mode  -> payment method ('UPI', 'Card', 'Cash')
--   order_time    -> timestamp of when the order was created
CREATE OR REPLACE TABLE workspace.kafka_demo.orders (
    order_id INT,
    customer_name STRING,
    city STRING,
    product STRING,
    amount DOUBLE,
    payment_mode STRING,
    order_time TIMESTAMP
);

-- Quick check: verify the empty table was created with all 7 columns.
SELECT * FROM workspace.kafka_demo.orders;
